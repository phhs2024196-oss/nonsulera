/** 축별 선호 뚜렷함: pct는 첫 번째 극 비율(0~100) */
export function clarity(pct: number) {
  const d = Math.abs(pct - 50);
  return d >= 20 ? "뚜렷함" : d >= 8 ? "약간" : "경계";
}

